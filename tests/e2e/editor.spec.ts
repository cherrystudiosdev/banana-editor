async function openDialog(paths: string[]): Promise<void> {
  await desktop.evaluate(({ dialog }, chosen) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: chosen }); }, paths);
}
async function saveDialog(file: string): Promise<void> {
  await desktop.evaluate(({ dialog }, chosen) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: chosen }); }, file);
}
async function menu(label: string, item: string): Promise<void> {
  await desktop.evaluate(({ Menu }, labels) => {
    const parent = Menu.getApplicationMenu()?.items.find(v => v.label === labels[0]);
    const command = parent?.submenu?.items.find(v => v.label === labels[1]);
    if (!command) throw new Error(`Menu item not found: ${labels.join(' / ')}`);
    command.click();
  }, [label, item]);
}
async function number(label: string, value: number): Promise<void> {
  const field = page.getByRole('spinbutton', { name: label, exact: true }).first();
  await field.fill(String(value)); await field.press('Enter');
}
async function savedProject(file: string): Promise<Project> {
  await saveDialog(file); await menu('File', 'Save as');
  await expect.poll(async () => { try { return (await fs.stat(file)).size; } catch { return 0; } }).toBeGreaterThan(50);
  return validateProject(JSON.parse(await fs.readFile(file, 'utf8')));
}
async function launchDesktop(userData: string): Promise<void> {
  const env: Record<string, string> = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined)), BANANA_E2E_USER_DATA: userData }; delete env.ELECTRON_RUN_AS_NODE;
  desktop = await _electron.launch({ executablePath: electronPath, args: [path.join(root, 'tests', 'e2e', 'launch.cjs')], cwd: root, env });
  page = await desktop.firstWindow();
  page.on('pageerror', error => errors.push(error.message));
  await expect(page.getByRole('button', { name: 'Import media', exact: true }).first()).toBeVisible();
}

