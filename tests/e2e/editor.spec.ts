test('isolated renderer security, offline startup and small-screen layout', async () => {
  expect(await page.evaluate(() => typeof (window as unknown as { require?: unknown }).require)).toBe('undefined');
  expect(await page.evaluate(() => typeof (window as unknown as { process?: unknown }).process)).toBe('undefined');
  expect(await page.locator('meta[http-equiv="Content-Security-Policy"]').getAttribute('content')).toContain("script-src 'self'");
  expect(await page.evaluate(() => Object.keys(window.banana))).not.toContain('exec');
  await page.evaluate(() => { window.open('https://example.com'); });
  expect(desktop.windows()).toHaveLength(1);
  const state = await page.evaluate(async () => ({ settings: await window.banana.settings(), info: await window.banana.info() }));
  expect(state.settings.aiEnabled).toBe(false); expect(state.settings.keyStatus).toEqual({ openai: false, gemini: false }); expect(state.info.ffmpeg).toBe(true);
  await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]!.setContentSize(1366, 768));
  await page.setViewportSize({ width: 1366, height: 768 });
  await expect(page.getByRole('button', { name: 'Import media', exact: true }).first()).toBeVisible();
  await expect(page.locator('.timeline')).toBeVisible();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
  expect(overflow).toBe(false);
  expect(await page.evaluate(() => [window.innerWidth, window.innerHeight])).toEqual([1366, 768]);
  await page.screenshot({ path: path.join(outputDir, 'editor-1366.png'), fullPage: true, scale: 'css' });
  expect(errors).toEqual([]);
});
